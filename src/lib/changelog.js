/**
 * 把 GitHub Release 正文（markdown）压成可读的纯文本行。
 * 只做去符号，不做富文本渲染 —— 弹窗里要的是"看得清"，不是排版。
 */
export function plainLines(text) {
  return String(text || '')
    .split('\n')
    .map((l) =>
      l
        .replace(/^#{1,6}\s*/, '')
        .replace(/\*\*(.*?)\*\*/g, '$1')
        .replace(/`([^`]*)`/g, '$1')
        .replace(/^\s*[-*+]\s+/, '• ')
        .trim(),
    )
    .filter((l) => l && !/^[-=]{3,}$/.test(l))
}

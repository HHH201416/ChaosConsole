export function translate(lang, key, vars) {
  const table = DICT[lang === 'en' ? 'en' : 'zh'] || DICT.zh
  let text = table[key] !== undefined ? table[key] : DICT.zh[key] !== undefined ? DICT.zh[key] : key
  if (vars && typeof vars === 'object') {
    text = text.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`))
  }
  return text
}

export function hasKey(lang, key) {
  return Boolean(DICT[lang] && Object.prototype.hasOwnProperty.call(DICT[lang], key))
}

